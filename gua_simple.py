def get_gua_name_simple(yao_list):
    """
    简单卦名计算（避免复杂操作）
    
    Args:
        yao_list: 从下往上的 6 爻列表 [初爻，二爻，三爻，四爻，五爻，上爻]
    
    Returns:
        str: 卦名
    """
    # 转换为二进制
    binary = []
    for yao in yao_list:
        if yao in [7, 9]:  # 阳爻
            binary.append(1)
        else:  # 阴爻 (6, 8)
            binary.append(0)
    
    return GUA_MAP.get(tuple(binary), '未知卦')


def get_gua_txt_simple(gua_name):
    """
    简单读取 txt 文件（保守版本）
    
    Args:
        gua_name: 卦名
    
    Returns:
        str: txt 文件完整内容，或 None
    """
    try:
        import os
        data_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data')
        
        # 提取卦名
        simple_name = gua_name.replace('卦', '')
        txt_file = os.path.join(data_dir, f'{simple_name}卦.txt')
        
        if not os.path.exists(txt_file):
            return None
        
        with open(txt_file, 'r', encoding='utf-8') as f:
            content = f.read()
        
        return content
    except Exception as e:
        print(f'[ERROR] Read txt failed: {e}')
        return None


